//! Generates a genuine BN254 Groth16 proof for a tiny circuit and writes the
//! verification material as Rust constants for the contract-side spike.
//!
//! This is a real proof: a real random parameter setup, a real proving run, and
//! a real verifying key. It is NOT a RISC Zero receipt, and the circuit is a
//! single multiplication constraint used only to exercise the verification
//! path. RISC Zero's seal encoding, ImageID binding, and digest check are a
//! separate, still-open step.
//!
//! Output file: `../groth16-verify/src/vector.rs` (generated, reproducible).

use ark_bn254::{Bn254, Fr};
use ark_ff::PrimeField;
use ark_groth16::{Groth16, Proof, VerifyingKey};
use ark_relations::{
    lc,
    r1cs::{ConstraintSynthesizer, ConstraintSystemRef, SynthesisError},
};
use ark_serialize::{CanonicalDeserialize, CanonicalSerialize};
use ark_snark::SNARK;
use ark_std::rand::SeedableRng;
use rand::rngs::StdRng;
use std::fs;
use std::path::Path;

/// c = a * b, with c as the single public input.
#[derive(Copy, Clone)]
struct MulCircuit {
    a: Fr,
    b: Fr,
}

impl ConstraintSynthesizer<Fr> for MulCircuit {
    fn generate_constraints(self, cs: ConstraintSystemRef<Fr>) -> Result<(), SynthesisError> {
        let a = cs.new_witness_variable(|| Ok(self.a))?;
        let b = cs.new_witness_variable(|| Ok(self.b))?;
        let c = cs.new_input_variable(|| Ok(self.a * self.b))?;
        cs.enforce_constraint(lc!() + a, lc!() + b, lc!() + c)?;
        Ok(())
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn main() {
    // Fixed seed: the generated material is reproducible for review.
    let mut rng = StdRng::seed_from_u64(0x1d3a4);

    let a = Fr::from(6u64);
    let b = Fr::from(7u64);
    let circuit = MulCircuit { a, b };

    let (pk, vk) = Groth16::<Bn254>::circuit_specific_setup(circuit, &mut rng).unwrap();
    let proof = Groth16::<Bn254>::prove(&pk, circuit, &mut rng).unwrap();

    let public_input = a * b;
    assert!(
        Groth16::<Bn254>::verify_proof(&ark_groth16::prepare_verifying_key(&vk), &proof, &[public_input])
            .unwrap(),
        "generated proof must verify natively"
    );

    let mut vk_bytes = Vec::new();
    vk.serialize_compressed(&mut vk_bytes).unwrap();
    let mut proof_bytes = Vec::new();
    proof.serialize_compressed(&mut proof_bytes).unwrap();
    let mut input_bytes = Vec::new();
    public_input.serialize_compressed(&mut input_bytes).unwrap();

    // Sanity: the serialized forms must round-trip through the same code path
    // the contract uses.
    let vk_back = VerifyingKey::<Bn254>::deserialize_compressed(&vk_bytes[..]).unwrap();
    let proof_back = Proof::<Bn254>::deserialize_compressed(&proof_bytes[..]).unwrap();
    let input_back = Fr::deserialize_compressed(&input_bytes[..]).unwrap();
    assert!(
        Groth16::<Bn254>::verify_proof(
            &ark_groth16::prepare_verifying_key(&vk_back),
            &proof_back,
            &[input_back],
        )
        .unwrap(),
        "round-tripped material must verify"
    );

    let out = format!(
        "// Generated by `cargo run --release` in spikes/proofgen. Do not edit.\n\
         // BN254 Groth16 material for: c = a * b with c public (a = 6, b = 7).\n\
         // Sizes: vk = {} bytes, proof = {} bytes, public input = {} bytes.\n\n\
         pub const VK: &[u8] = &{};\n\n\
         pub const PROOF: &[u8] = &{};\n\n\
         pub const PUBLIC_INPUT: [u8; {}] = {};\n",
        vk_bytes.len(),
        proof_bytes.len(),
        input_bytes.len(),
        byte_literal(&vk_bytes),
        byte_literal(&proof_bytes),
        input_bytes.len(),
        byte_literal(&input_bytes),
    );

    let path = Path::new("../groth16-verify/src/vector.rs");
    fs::write(path, out).expect("write vector.rs");
    println!(
        "wrote {}: vk={} bytes proof={} bytes input={} bytes",
        path.display(),
        vk_bytes.len(),
        proof_bytes.len(),
        input_bytes.len()
    );
}

fn byte_literal(bytes: &[u8]) -> String {
    let mut s = String::from("[");
    for (i, b) in bytes.iter().enumerate() {
        if i % 16 == 0 {
            s.push_str("\n    ");
        }
        s.push_str(&format!("0x{b:02x}, "));
    }
    s.push_str("\n]");
    s
}
