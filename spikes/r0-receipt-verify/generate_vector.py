#!/usr/bin/env python3
"""Generate receipt_vector.rs from a real receipt produced by spikes/r0-receipt.

Run from anywhere; paths are resolved relative to this file.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE.parent / "r0-receipt" / "dist" / "receipt.json"
TARGET = HERE / "src" / "receipt_vector.rs"


def byte_array(name: str, hex_str: str, indent: str = "    ") -> str:
    raw = bytes.fromhex(hex_str)
    rows = []
    for i in range(0, len(raw), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in raw[i : i + 12])
        rows.append(f"{indent}{chunk},")
    body = "\n".join(rows)
    return f"pub const {name}: [u8; {len(raw)}] = [\n{body}\n];\n"


def slice_literal(name: str, hex_str: str) -> str:
    raw = bytes.fromhex(hex_str)
    rows = []
    for i in range(0, len(raw), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in raw[i : i + 12])
        rows.append(f"    {chunk},")
    body = "\n".join(rows)
    return f"pub const {name}: &[u8] = &[\n{body}\n];\n"


def main() -> None:
    receipt = json.loads(SOURCE.read_text())
    parts = [
        "// Generated by generate_vector.py from spikes/r0-receipt/dist/receipt.json.",
        "// Do not edit by hand.",
        f"// image_id: {receipt['image_id']}",
        f"// seal: {receipt['seal_bytes']} bytes, journal: {receipt['journal_len']} bytes",
        "",
        slice_literal("SEAL", receipt["seal"]),
        byte_array("CLAIM_DIGEST", receipt["claim_digest"]),
        byte_array("CONTROL_ROOT", receipt["control_root"]),
        byte_array("BN254_CONTROL_ID", receipt["bn254_control_id"]),
    ]
    TARGET.write_text("\n".join(parts))
    print(f"wrote {TARGET} (seal {receipt['seal_bytes']} bytes)")


if __name__ == "__main__":
    main()
